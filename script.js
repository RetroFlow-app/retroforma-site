  function deleteProject(item) {
    if (item.type === "custom") {
      const items = normalizeCustom(PROJECT_CUSTOM_KEY, "project");
      items.splice(item.customIndex, 1);
      writeJson(PROJECT_CUSTOM_KEY, items);
    } else {
      writeJson(PROJECT_HIDDEN_KEY, [...new Set([...list(PROJECT_HIDDEN_KEY), item.id])]);
    }
    removeOrder("project", item.orderId);
    refreshAdmin();
  }

  function deleteProduct(item) {
    if (item.type === "custom") {
      const items = normalizeCustom(PRODUCT_CUSTOM_KEY, "product");
      items.splice(item.customIndex, 1);
      writeJson(PRODUCT_CUSTOM_KEY, items);
    } else {
      writeJson(PRODUCT_HIDDEN_KEY, [...new Set([...list(PRODUCT_HIDDEN_KEY), item.id])]);
    }
    removeOrder("product", item.orderId);
    refreshAdmin();
  }

