/* RetroForma admin image preview v1 */
(() => {
  if (document.body?.dataset.adminPage !== "true") return;

  function splitImageValues(value) {
    return String(value || "")
      .split(",")
      .map((item) => item.trim())
      .filter(Boolean);
  }

  function resolveImageSrc(src) {
    if (!src) return "";
    if (/^(data:|blob:|https?:|file:)/i.test(src)) return src;
    return src.replace(/^\.\//, "");
  }

  function renderPathPreview(input) {
    const label = input.closest("label");
    if (!label) return;
    let preview = label.querySelector(".rf-image-preview");
    if (!preview) {
      preview = document.createElement("div");
      preview.className = "rf-image-preview";
      label.appendChild(preview);
    }

    const images = splitImageValues(input.value);
    const signature = images.join("|");
    if (preview.dataset.signature === signature) return;
    preview.dataset.signature = signature;
    preview.innerHTML = images.length
      ? images.map((src) => '<figure><img src="' + resolveImageSrc(src) + '" alt=""><figcaption>' + src + '</figcaption></figure>').join("")
      : '<span class="rf-image-preview-empty">Brak zdjęć</span>';
  }

  function renderFilePreview(input) {
    const label = input.closest("label");
    if (!label) return;
    let preview = label.querySelector(".rf-image-preview");
    if (!preview) {
      preview = document.createElement("div");
      preview.className = "rf-image-preview";
      label.appendChild(preview);
    }

    const files = Array.from(input.files || []);
    const signature = files.map((file) => file.name + ":" + file.size).join("|");
    if (preview.dataset.signature === signature) return;
    preview.dataset.signature = signature;
    preview.innerHTML = files.length
      ? files.map((file) => '<figure><img src="' + URL.createObjectURL(file) + '" alt=""><figcaption>' + file.name + '</figcaption></figure>').join("")
      : '<span class="rf-image-preview-empty">Po wybraniu zdjęć zobaczysz miniatury tutaj</span>';
  }

  function enhanceImagePreviews() {
    document.querySelectorAll('.rf-real-row input[name="images"]').forEach((input) => {
      if (!input.dataset.previewBound) {
        input.dataset.previewBound = "1";
        input.addEventListener("input", () => renderPathPreview(input));
        input.addEventListener("change", () => renderPathPreview(input));
      }
      renderPathPreview(input);
    });

    document.querySelectorAll('#projectForm input[type="file"], #productForm input[type="file"]').forEach((input) => {
      if (!input.dataset.previewBound) {
        input.dataset.previewBound = "1";
        input.addEventListener("change", () => renderFilePreview(input));
      }
      renderFilePreview(input);
    });
  }

  let previewTimer = null;
  const observer = new MutationObserver(() => {
    clearTimeout(previewTimer);
    previewTimer = setTimeout(enhanceImagePreviews, 80);
  });
  observer.observe(document.body, { childList: true, subtree: true });
  window.addEventListener("load", enhanceImagePreviews);
  document.addEventListener("DOMContentLoaded", enhanceImagePreviews);
  setTimeout(enhanceImagePreviews, 250);
})();


