  function readJson(key, fallback) {
    try {
      const value = JSON.parse(localStorage.getItem(key) || JSON.stringify(fallback));
      return value ?? fallback;
    } catch {
      return fallback;
    }
  }

  function writeJson(key, value) {
    localStorage.setItem(key, JSON.stringify(value));
  }

  function list(key) {
    const value = readJson(key, []);
    return Array.isArray(value) ? value : [];
  }

  function map(key) {
    const value = readJson(key, {});
    return value && typeof value === "object" && !Array.isArray(value) ? value : {};
  }

  function newId(prefix) {
    return prefix + "-" + Date.now() + "-" + Math.random().toString(36).slice(2, 8);
  }

  function normalizeCustom(key, prefix) {
    const items = readJson(key, []);
    if (!Array.isArray(items)) return [];
    let changed = false;
    const normalized = items.map((item) => {
      if (item?.id) return item;
      changed = true;
      return { ...item, id: newId(prefix) };
    });
    if (changed) writeJson(key, normalized);
    return normalized;
  }

  function splitImages(value, fallback) {
    const images = String(value || "").split(",").map((item) => item.trim()).filter(Boolean);
    return images.length ? images : (fallback || []).filter(Boolean);
  }

  function esc(value) {
    return String(value || "").replace(/&/g,"&amp;").replace(/</g,"&lt;").replace(/>/g,"&gt;").replace(/"/g,"&quot;");
  }

  function ordered(items, orderKey) {
    const order = list(orderKey);
    const rank = new Map(order.map((id, index) => [id, index]));
    return items.map((item, index) => ({...item, fallbackIndex:index})).sort((a,b) => {
      const ar = rank.has(a.orderId) ? rank.get(a.orderId) : Number.MAX_SAFE_INTEGER + a.fallbackIndex;
      const br = rank.has(b.orderId) ? rank.get(b.orderId) : Number.MAX_SAFE_INTEGER + b.fallbackIndex;
      return ar - br;
    }).map((item, index, all) => ({...item, canUp:index>0, canDown:index<all.length-1}));
  }

  function projectItems() {
    const hidden = new Set(list(PROJECT_HIDDEN_KEY));
    const overrides = map(PROJECT_OVERRIDE_KEY);
    const defaults = defaultProjectData.filter((item) => !hidden.has(item.id)).map((item) => {
      const override = overrides[item.id] || {};
      const images = override.images || item.images;
      return {...item, ...override, images, type:"default", orderId:"project-default:" + item.id};
    });
    const custom = normalizeCustom(PROJECT_CUSTOM_KEY, "project").map((item, index) => {
      const images = Array.isArray(item.images) && item.images.length ? item.images : [item.image].filter(Boolean);
      return {...item, images, type:"custom", customIndex:index, orderId:"project-custom:" + item.id};
    });
    return ordered([...defaults, ...custom], PROJECT_ORDER_KEY);
  }

  function productItems() {
    const hidden = new Set(list(PRODUCT_HIDDEN_KEY));
    const overrides = map(PRODUCT_OVERRIDE_KEY);
    const defaults = defaultProductData.filter((item) => !hidden.has(item.id)).map((item) => {
      const override = overrides[item.id] || {};
      const images = override.images || item.images;
      return {...item, ...override, images, type:"default", orderId:"product-default:" + item.id};
    });
    const custom = normalizeCustom(PRODUCT_CUSTOM_KEY, "product").map((item, index) => {
      const images = Array.isArray(item.images) && item.images.length ? item.images : [item.image].filter(Boolean);
      return {...item, images, type:"custom", customIndex:index, orderId:"product-custom:" + item.id};
    });
    return ordered([...defaults, ...custom], PRODUCT_ORDER_KEY);
  }

  function setOrder(kind, items) {
    writeJson(kind === "project" ? PROJECT_ORDER_KEY : PRODUCT_ORDER_KEY, items.map((item) => item.orderId));
  }

  function move(kind, orderId, direction) {
    const items = kind === "project" ? projectItems() : productItems();
    const index = items.findIndex((item) => item.orderId === orderId);
    const next = index + direction;
    if (index < 0 || next < 0 || next >= items.length) return;
    [items[index], items[next]] = [items[next], items[index]];
    setOrder(kind, items);
    refreshAdmin();
  }

  function removeOrder(kind, orderId) {
    const key = kind === "project" ? PROJECT_ORDER_KEY : PRODUCT_ORDER_KEY;
    writeJson(key, list(key).filter((id) => id !== orderId));
  }

  function field(label, name, value, textarea=false) {
    return `<label><span>${label}</span>${textarea ? `<textarea name="${name}" rows="3">${esc(value)}</textarea>` : `<input type="text" name="${name}" value="${esc(value)}">`}</label>`;
  }

  function saveProject(item, form) {
    const data = new FormData(form);
    const images = splitImages(data.get("images"), item.images);
    const next = {
      title: String(data.get("title") || "").trim(),
      description: String(data.get("description") || "").trim(),
      tag: String(data.get("tag") || "").trim(),
      price: String(data.get("price") || "").trim(),
      shipping: String(data.get("shipping") || "").trim(),
      leadTime: String(data.get("leadTime") || "").trim(),
      payment: String(data.get("payment") || "").trim(),
      availableForOrder: data.get("availableForOrder") === "on",
      image: images[0] || "",
      images,
      alt: String(data.get("title") || "").trim()
    };
    if (!next.title || !next.description) return;
    if (item.type === "custom") {
      const items = normalizeCustom(PROJECT_CUSTOM_KEY, "project");
      items[item.customIndex] = {...items[item.customIndex], ...next};
      writeJson(PROJECT_CUSTOM_KEY, items);
    } else {
      const overrides = map(PROJECT_OVERRIDE_KEY);
      overrides[item.id] = next;
      writeJson(PROJECT_OVERRIDE_KEY, overrides);
    }
    refreshAdmin();
  }

